#!/usr/bin/env node
// Generates src/theme/tokens.generated.ts from the single source of truth,
// design/tokens/recipebox.tokens.json (ADR 0019). Never edit the output by hand.
//   node scripts/generate-tokens.mjs           write the file
//   node scripts/generate-tokens.mjs --check   fail if the file is out of date (CI)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "..", "design", "tokens", "recipebox.tokens.json");
const target = join(here, "..", "src", "theme", "tokens.generated.ts");
const t = JSON.parse(readFileSync(source, "utf8"));

const colors = { light: {}, dark: {} };
for (const [name, v] of Object.entries(t.color)) for (const ap of t.appearances) colors[ap][name] = v[ap];

const out = `// GENERATED by apps/mobile/scripts/generate-tokens.mjs from design/tokens/recipebox.tokens.json.
// Do not edit by hand. Token set version ${t.version}.
/* eslint-disable */

export const tokenVersion = ${JSON.stringify(t.version)} as const;

export const colors = ${JSON.stringify(colors, null, 2)} as const;

export type ColorName = keyof typeof colors.light;
export type ColorTokens = { readonly [K in ColorName]: string };

export const typography = ${JSON.stringify(t.typography.roles, null, 2)} as const;

export const typeScaling = ${JSON.stringify(t.typography.scaling, null, 2)} as const;

export const space = ${JSON.stringify(t.space, null, 2)} as const;

export const radius = ${JSON.stringify(t.radius, null, 2)} as const;

export const touch = ${JSON.stringify(t.touch, null, 2)} as const;

export const motion = ${JSON.stringify(t.motion, null, 2)} as const;

export const elevation = ${JSON.stringify(Object.fromEntries(Object.entries(t.elevation).filter(([k]) => !k.startsWith("$"))), null, 2)} as const;
`;

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("tokens.generated.ts is out of date. Run: node scripts/generate-tokens.mjs");
    process.exit(1);
  }
  console.log("tokens.generated.ts matches design/tokens/recipebox.tokens.json");
} else {
  writeFileSync(target, out);
  console.log("wrote src/theme/tokens.generated.ts");
}
