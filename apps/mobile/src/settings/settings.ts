// Device-local settings, as pure rules.
//
// No React Native imports here, so these run under `node --test` as well as in
// the app. Appearance is the exception and lives in theme/appearance.ts: it has
// to be read and applied before the first frame, so it is loaded on a different
// path from everything else.
//
// Every setting here is local to the device and unsynced (ADR 0004). A phone
// and a tablet may reasonably want different defaults, and all of this has to
// work before there is an account to attach it to.
import type { Measurement } from "../domain/convert";

export const MEASUREMENT_KEY = "settings.measurement";
export const TIMER_SOUND_KEY = "settings.timerSound";

/** What a newly opened recipe shows before anyone touches the selector.
 *
 *  "original" is the default on purpose. It is the only option that is always
 *  faithful: a conversion can be unavailable (an ingredient with no density we
 *  know) or misleading, and ADR 0012 keeps the imported quantities as written.
 *  A cook who wants metric everywhere can say so here; nobody gets converted
 *  numbers they did not ask for. */
export const DEFAULT_MEASUREMENT: Measurement = "original";

export const MEASUREMENT_CHOICES: readonly { value: Measurement; label: string; detail: string }[] = [
  { value: "original", label: "As written", detail: "The units the recipe was imported with" },
  { value: "us", label: "US customary", detail: "Cups, ounces and Fahrenheit where a conversion is reliable" },
  { value: "metric", label: "Metric", detail: "Grams, millilitres and Celsius where a conversion is reliable" },
];

export function parseMeasurement(stored: unknown): Measurement {
  return stored === "original" || stored === "us" || stored === "metric" ? stored : DEFAULT_MEASUREMENT;
}

/**
 * A timer alert sound.
 *
 * `file` is the name as it sits in the app bundle, which is what the OS wants;
 * `null` means the system's own notification sound. The files are generated by
 * scripts/generate-timer-sounds.mjs and registered in app.json, so this list
 * and that script have to agree -- soundsAreRegistered() in the test checks it.
 */
export type TimerSound = "system" | "chime" | "bell" | "ring";

export const DEFAULT_TIMER_SOUND: TimerSound = "chime";

export const TIMER_SOUND_CHOICES: readonly {
  value: TimerSound;
  label: string;
  detail: string;
  file: string | null;
}[] = [
  { value: "chime", label: "Chime", detail: "Two soft notes", file: "chime.wav" },
  { value: "bell", label: "Bell", detail: "One low note, long tail", file: "bell.wav" },
  { value: "ring", label: "Ring", detail: "Four quick notes, carries further", file: "ring.wav" },
  { value: "system", label: "System default", detail: "Whatever your device uses for notifications", file: null },
];

export function parseTimerSound(stored: unknown): TimerSound {
  return TIMER_SOUND_CHOICES.some((c) => c.value === stored)
    ? (stored as TimerSound)
    : DEFAULT_TIMER_SOUND;
}

/** The bundle filename for a sound, or null for the system sound. */
export function timerSoundFile(sound: TimerSound): string | null {
  return TIMER_SOUND_CHOICES.find((c) => c.value === sound)?.file ?? null;
}

export function timerSoundLabel(sound: TimerSound): string {
  return TIMER_SOUND_CHOICES.find((c) => c.value === sound)?.label ?? "System default";
}

/**
 * The Android notification channel for a sound.
 *
 * Android fixes a channel's sound when the channel is created and will not
 * change it afterwards -- by design, so an app cannot override a choice the
 * user made in system settings. The only way to offer a choice is a channel per
 * sound, which is why this exists and why the Android Settings app will show
 * RecipeBox with several timer channels. Documented in
 * docs/timers-and-notifications.md.
 */
export function timerChannelId(sound: TimerSound): string {
  return `timers-${sound}`;
}

export type Settings = { measurement: Measurement; timerSound: TimerSound };

export const DEFAULT_SETTINGS: Settings = {
  measurement: DEFAULT_MEASUREMENT,
  timerSound: DEFAULT_TIMER_SOUND,
};
