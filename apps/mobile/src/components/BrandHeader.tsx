// The RecipeBox lockup, assembled rather than pasted.
//
// Both pieces come from the approved concept board, but neither carries a
// ground of its own, so the header sits directly on the canvas in either
// appearance with no rectangle behind it:
//
//   brand-symbol.png        the cookbook, isolated by flooding the board's
//                           cream in from the border and unmixing it back out
//                           of the antialiased edge, so no pale halo appears
//                           on a dark surface.
//   brand-wordmark-mask.png the board's own letterforms as an alpha mask with
//                           no colour, tinted here with the `text` token.
//
// Regenerated by design/brand/extract.mjs. Nothing here is redrawn.
//
// Both images are given an explicit width AND height in points. Relying on
// `aspectRatio` alone leaves one axis to be derived, and if the other arrives
// non-finite the style is dropped and the artwork lays out at its intrinsic
// 512x592 -- which is how this header once filled an entire screen.
import { Image, StyleSheet, View } from "react-native";
import { useTheme } from "../theme/ThemeProvider";
import { artworkScale } from "../theme/appearance";

const SYMBOL = require("../../assets/brand-symbol.png");
const WORDMARK = require("../../assets/brand-wordmark-mask.png");

// The crops' own ratios; see design/brand/README.md.
const SYMBOL_ASPECT = 0.8649;
const WORDMARK_ASPECT = 4.4586;

/** Wordmark cap height against the symbol's full height, so the two sit on a
 *  shared optical baseline rather than a shared bounding box. */
const WORDMARK_RATIO = 0.63;

export function BrandHeader({ size = "large" }: { size?: "large" | "compact" }) {
  const t = useTheme();
  const scale = artworkScale(t.fontScale);
  const base = size === "large" ? 34 : 24;

  const symbolH = Math.round(base * scale);
  const symbolW = Math.round(symbolH * SYMBOL_ASPECT);
  const wordmarkH = Math.round(base * WORDMARK_RATIO * scale);
  const wordmarkW = Math.round(wordmarkH * WORDMARK_ASPECT);

  return (
    <View
      style={styles.row}
      accessible
      accessibilityRole="header"
      accessibilityLabel="RecipeBox"
    >
      <Image
        source={SYMBOL}
        style={{ width: symbolW, height: symbolH }}
        resizeMode="contain"
      />
      <Image
        source={WORDMARK}
        style={{ width: wordmarkW, height: wordmarkH, tintColor: t.colors.text }}
        resizeMode="contain"
      />
    </View>
  );
}

const styles = StyleSheet.create({
  row: { flexDirection: "row", alignItems: "center", gap: 10 },
});
