// The RecipeBox lockup, assembled rather than pasted.
//
// Both pieces come from the approved concept board, but neither carries a
// ground of its own, so the header sits directly on the canvas in either
// appearance with no rectangle behind it:
//
//   brand-symbol.png        the cookbook, isolated by flooding the board's
//                           cream in from the border and unmixing it back out
//                           of the antialiased edge, so no pale halo appears
//                           on a dark surface.
//   brand-wordmark-mask.png the board's own letterforms as an alpha mask with
//                           no colour, tinted here with the `text` token.
//
// Regenerated by design/brand/extract.mjs. Nothing here is redrawn.
import { Image, PixelRatio, StyleSheet, View } from "react-native";
import { useTheme } from "../theme/ThemeProvider";

const SYMBOL = require("../../assets/brand-symbol.png");
const WORDMARK = require("../../assets/brand-wordmark-mask.png");

// The crops' own ratios; see design/brand/README.md.
const SYMBOL_ASPECT = 0.8649;
const WORDMARK_ASPECT = 4.4586;

// Artwork does not scale with Dynamic Type on its own, so it is stepped by the
// font scale and capped, in the same way the rest of the app treats its marks.
const MAX_SCALE = 1.5;

export function BrandHeader({ size = "large" }: { size?: "large" | "compact" }) {
  const t = useTheme();
  const scale = Math.min(PixelRatio.getFontScale(), MAX_SCALE);
  const base = size === "large" ? 34 : 24;
  const symbolHeight = Math.round(base * scale);
  // The wordmark's cap height is smaller than the symbol's full height; this
  // ratio sits the two on a shared optical baseline.
  const wordmarkHeight = Math.round(base * 0.63 * scale);

  return (
    <View
      style={styles.row}
      accessible
      accessibilityRole="header"
      accessibilityLabel="RecipeBox"
    >
      <Image
        source={SYMBOL}
        style={{ height: symbolHeight, aspectRatio: SYMBOL_ASPECT }}
        resizeMode="contain"
      />
      <Image
        source={WORDMARK}
        style={{
          height: wordmarkHeight,
          aspectRatio: WORDMARK_ASPECT,
          tintColor: t.colors.text,
          maxWidth: "100%",
        }}
        resizeMode="contain"
      />
    </View>
  );
}

const styles = StyleSheet.create({
  row: { flexDirection: "row", alignItems: "center", gap: 10 },
});
